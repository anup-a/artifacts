function symbol(id, name) {
  const svg = readFileSync(mod(`lucide-static/icons/${name}.svg`), "utf8");
  const body = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"))
    .split("\n").map((l) => l.trim()).filter(Boolean).join("");
  return `  <symbol id="i-${id}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`;
}

// The mark and the GitHub logo are not Lucide icons: they come from the
// public sprite unchanged.
const shared = readFileSync(join(root, "internal/app/templates/partials/icons.html"), "utf8")
  .split("\n").filter((l) => /id="i-(mark|github)"/.test(l)).map((l) => l.trimEnd());
const lucideVersion = JSON.parse(readFileSync(mod("lucide-static/package.json"), "utf8")).version;
writeFileSync(
  join(root, "internal/app/templates/partials/lucide.html"),
  [
    `{{/* Generated by web/build.mjs from lucide-static ${lucideVersion} (ISC). Do not edit. */}}`,
    `{{define "sprite-ui"}}`,
    `<svg hidden aria-hidden="true" xmlns="http://www.w3.org/2000/svg">`,
    ...shared,
    ...Object.entries(icons).map(([id, name]) => symbol(id, name)),
    `</svg>`,
    `{{end}}`,
    "",
  ].join("\n"),
);
