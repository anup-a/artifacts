// Builds the dashboard's assets from Tailwind CSS, Basecoat (shadcn/ui as
// plain HTML) and Lucide, into files the Go server embeds:
//
//   internal/app/static/dashboard.css          Tailwind + Basecoat + src/dashboard.css
//   internal/app/static/basecoat.js            the Basecoat behaviours the dashboard uses
//   internal/app/templates/partials/lucide.html  the icon sprite, as a template
//
// All three are committed so `go build` never needs Node. CI rebuilds them
// and fails if the checked-in copies are stale.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const mod = (p) => join(here, "node_modules", p);

// ---- CSS -----------------------------------------------------------------
execFileSync(mod(".bin/tailwindcss"), [
  "-i", join(here, "src/dashboard.css"),
  "-o", join(root, "internal/app/static/dashboard.css"),
  "--minify",
], { stdio: "inherit", cwd: here });

// ---- JS ------------------------------------------------------------------
// The runtime first, then each component it registers. Basecoat starts every
// registered component on DOMContentLoaded and watches for new ones, so the
// side peek's fragments get working menus too.
const js = ["basecoat", "dropdown-menu", "sidebar", "tabs", "toast"]
  .map((name) => readFileSync(mod(`basecoat-css/dist/js/${name}.min.js`), "utf8").trim())
  .join("\n");
const version = JSON.parse(readFileSync(mod("basecoat-css/package.json"), "utf8")).version;
writeFileSync(
  join(root, "internal/app/static/basecoat.js"),
  `/* Basecoat ${version} (MIT), built by web/build.mjs: runtime, dropdown-menu, sidebar, tabs, toast. */\n${js}\n`,
);

// ---- Icons ---------------------------------------------------------------
